#!/usr/bin/env node
/**
 * The rule registry, generated from the engines that actually emit the rules.
 * Original work, MIT.
 *
 *   node tools/build-rule-registry.mjs            write product/rules.json
 *   node tools/build-rule-registry.mjs --check    fail if it is out of date
 *
 * Why generated rather than written.
 *
 * SiteSmith's refusal classes live in `gate.mjs` as strings passed to `refuse()`. A
 * hand-written registry beside them is a second list of the same thing, and two lists of the
 * same thing disagree within a month: a class gets renamed, a class gets added, and the
 * document that was supposed to make the rules legible starts describing rules that are not
 * there. So the structure comes from the code, every time.
 *
 * What cannot be generated is judgement: what evidence a rule rests on, how likely it is to
 * be wrong, and what a builder does about it when it is. That lives in
 * `product/rule-notes.json`, hand-written, and this refuses to build a registry for a class
 * that has no note. A new refusal class therefore cannot ship without somebody saying what
 * it is for and how it can be wrong.
 *
 * This changes no rule's semantics. It is a description of what already runs, and
 * docs/GATE-POLICY.md still governs what may become a hard gate.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const OUT = join(ROOT, 'product/rules.json');
const NOTES = join(ROOT, 'product/rule-notes.json');

const ENGINES = {
  'skills/sitesmith-v3/scripts/gate.mjs': /(refuse|warn|assetRefusal|tell)\(\s*'([a-z-]+\/[a-z-]+)'/g,
};

/* Which surfaces a class can fire on, read from the code rather than declared. A class
   guarded by a scenario check is scoped to it; everything else applies everywhere. */
const SURFACE_GUARD = {
  'operate/nothing-to-do-on-the-first-screen': ['operate'],
  'journeys/none': ['buy', 'operate', 'redesign'],
  'journeys/empty': ['buy', 'operate', 'redesign'],
};

const notes = JSON.parse(readFileSync(NOTES, 'utf8'));
const found = new Map();

for (const [file, re] of Object.entries(ENGINES)) {
  const src = readFileSync(join(ROOT, file), 'utf8');
  for (const m of src.matchAll(re)) {
    const id = m[2];
    const cur = found.get(id) ?? { id, engines: new Set(), calls: new Set() };
    cur.engines.add(file);
    cur.calls.add(m[1]);
    found.set(id, cur);
  }
}

const missing = [...found.keys()].filter((id) => !notes.rules[id]);
const orphan = Object.keys(notes.rules).filter((id) => !found.has(id));

if (missing.length || orphan.length) {
  if (missing.length) {
    console.error(`\n  ${missing.length} rule(s) emitted by an engine and not described in product/rule-notes.json:\n`);
    for (const id of missing) console.error(`    ${id}`);
    console.error('\n  A refusal class needs somebody to say what it is for and how it can be wrong.');
    console.error('  Add: { "evidence": "...", "falsePositiveRisk": "low|medium|high", "override": "..." }\n');
  }
  if (orphan.length) {
    console.error(`\n  ${orphan.length} note(s) for rules no engine emits any more:\n`);
    for (const id of orphan) console.error(`    ${id}`);
    console.error('\n  Either the class was renamed, or the note outlived it. Remove the note.\n');
  }
  process.exit(1);
}

const rules = [...found.values()].sort((a, b) => a.id.localeCompare(b.id)).map((r) => {
  const n = notes.rules[r.id];
  return {
    id: r.id,
    category: r.id.split('/')[0],
    kind: n.kind ?? (r.calls.has('refuse') || r.calls.has('assetRefusal') || r.calls.has('tell') ? 'refusal' : 'advisory'),
    scope: SURFACE_GUARD[r.id] ?? 'any surface',
    severity: n.severity ?? 'blocking',
    engines: [...r.engines].sort(),
    appliesWhen: n.appliesWhen,
    evidence: n.evidence,
    falsePositiveRisk: n.falsePositiveRisk,
    override: n.override,
    fixtures: n.fixtures ?? { pass: null, fail: null },
    provenance: n.provenance ?? 'original',
    draftDowngrades: r.calls.has('assetRefusal') || r.calls.has('warn'),
  };
});

const out = {
  $comment: [
    'Generated by tools/build-rule-registry.mjs. Do not edit by hand: the structure comes',
    'from the engines that emit the rules, and the judgement comes from product/rule-notes.json.',
    '',
    'This describes what already runs. It changes no rule and promotes nothing to a hard gate;',
    'docs/GATE-POLICY.md still governs that. `falsePositiveRisk: unassessed` means no build in',
    'this repository has exercised the rule yet, which is a statement about the evidence and',
    'not about the rule.',
  ],
  schemaVersion: 1,
  counts: {
    total: rules.length,
    byCategory: Object.fromEntries(
      [...new Set(rules.map((r) => r.category))].sort()
        .map((c) => [c, rules.filter((r) => r.category === c).length]),
    ),
    byRisk: Object.fromEntries(
      ['low', 'medium', 'high', 'unassessed']
        .map((k) => [k, rules.filter((r) => r.falsePositiveRisk === k).length])
        .filter(([, n]) => n > 0),
    ),
  },
  rules,
};

const text = `${JSON.stringify(out, null, 2)}\n`;

if (process.argv.includes('--check')) {
  const on = (() => { try { return readFileSync(OUT, 'utf8'); } catch { return null; } })();
  if (on !== text) {
    console.error('\n  product/rules.json is out of date. Run: node tools/build-rule-registry.mjs\n');
    process.exit(1);
  }
  console.log(`\n  the registry describes all ${rules.length} rules the engines emit\n`);
  process.exit(0);
}

writeFileSync(OUT, text);
console.log(`\n  wrote product/rules.json: ${rules.length} rules, ${Object.keys(out.counts.byCategory).length} categories`);
console.log(`  risk: ${Object.entries(out.counts.byRisk).map(([k, n]) => `${n} ${k}`).join(', ')}\n`);
